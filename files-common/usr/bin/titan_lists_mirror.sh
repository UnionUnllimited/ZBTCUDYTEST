#!/bin/sh
# ═══════════════════════════════════════════════════════════════════
#  Titan Router — выбор живого зеркала списков маршрутизации
#
#  Зачем это вообще нужно.
#
#  Просится очевидное: перечислить все зеркала в chnlist_url — опция
#  списочная, PassWall их поддерживает. Так делать нельзя, и это не
#  предположение, а проверка на стенде 12.09.2026.
#
#  PassWall скачивает ВСЕ адреса из списка и складывает строки в одно
#  множество. Но при отказе любого адреса ставит sret=1, и тогда
#  выбрасывает результат целиком — вместе с тем, что успешно скачалось
#  с живых зеркал (rule_update.lua, ветка «部分或全部资源无法下载»).
#
#  Проверили так: урезали chnlist до 50 строк, прописали рабочее
#  зеркало и заведомо мёртвый адрес, запустили обновление. Список
#  остался на пятидесяти строках. То есть каждое добавленное зеркало
#  не страхует, а повышает шанс, что обновление не пройдёт вовсе.
#
#  Поэтому адрес в конфиге всегда ровно один, а выбирает его этот
#  скрипт: перебирает зеркала, первое ответившее прописывает в uci.
#
#  Запуск: из titan_pw_check.sh, не чаще раза в час. Своей строкой в
#  cron его не поставить — /etc/crontabs переживает sysupgrade, и новые
#  задания до проданных роутеров не доезжают никогда. А /usr/bin
#  приходит из образа целиком, и titan_pw_check.sh уже стоит в кроне
#  у всех.
# ═══════════════════════════════════════════════════════════════════

set -u

LOG_TAG="titan_lists"
STAMP="/tmp/titan_lists_mirror_at"
MIN_GAP=3600

# Порядок — это и есть приоритет. Первым идёт объектное хранилище:
# у него нет своего домена, который может уехать, и из России оно
# отвечает стабильнее собственных площадок.
MIRRORS="https://storage.yandexcloud.net/234588/lists
https://titanvps.pro/lists
https://vbotrouters.titanvps.click/lists"

log() { logger -t "$LOG_TAG" "$*"; }

# ── Не чаще раза в час ───────────────────────────────────────────
# Вызывает нас сторож, который ходит раз в минуту. Проба трёх зеркал
# каждую минуту — это шестьдесят лишних соединений в час ради данных,
# которые меняются раз в сутки.
#
# Отметка в /tmp, а не в /etc: после перезагрузки проверить зеркало
# заново полезно, сеть могла смениться.
if [ "${1:-}" != "--now" ] && [ -f "$STAMP" ]; then
    LAST="$(cat "$STAMP" 2>/dev/null | tr -dc '0-9')"
    NOW="$(date +%s)"
    if [ -n "${LAST:-}" ] && [ "$((NOW - LAST))" -ge 0 ] \
       && [ "$((NOW - LAST))" -lt "$MIN_GAP" ]; then
        exit 0
    fi
fi

# ── Проба ────────────────────────────────────────────────────────
# Тянем один байт заголовком Range. Сервер, не умеющий куски,
# отдаст файл целиком — на этот случай стоит общий предел времени.
probe() {
    curl -fsS --connect-timeout 8 --max-time 20 --range 0-0 \
         -o /dev/null "$1/proxy-ip.lst" 2>/dev/null
}

BASE=""
for m in $MIRRORS; do
    if probe "$m"; then
        BASE="$m"
        break
    fi
    log "зеркало не ответило: $m"
done

if [ -z "$BASE" ]; then
    # Ни одно не отозвалось — скорее всего нет интернета вообще.
    # Конфиг не трогаем: то, что там стоит, ничем не хуже.
    log "ни одно зеркало не ответило — адрес оставлен прежним"
    exit 1
fi

date +%s > "$STAMP" 2>/dev/null || true

# ── Прописываем, если изменилось ─────────────────────────────────
# Опция списочная, поэтому именно delete, а не set: set на списке
# оставил бы старые значения рядом с новым, и мы получили бы ровно ту
# беду, от которой этот скрипт и написан.
CHANGED=0
set -- "chnlist_url proxy-domains.lst" "chnroute_url proxy-ip.lst" "gfwlist_url proxy-domains.lst"
for pair in "$@"; do
    opt="${pair%% *}"
    file="${pair##* }"
    want="$BASE/$file"
    cur="$(uci -q get passwall.@global_rules[0].$opt 2>/dev/null || true)"
    if [ "$cur" != "$want" ]; then
        uci -q delete passwall.@global_rules[0]."$opt" 2>/dev/null || true
        uci -q add_list passwall.@global_rules[0]."$opt"="$want" || true
        CHANGED=1
    fi
done

if [ "$CHANGED" = 1 ]; then
    uci -q commit passwall || true
    log "зеркало списков: $BASE"
fi

exit 0
