#!/bin/sh
# ═══════════════════════════════════════════════════════════════════
#  Titan Router — выбор живого зеркала списков маршрутизации
#
#  Что делает: перебирает зеркала, первое ответившее прописывает в
#  chnlist_url, chnroute_url и gfwlist_url. Больше ничего. Службы не
#  трогает, файлы списков не трогает, сеть не перенастраивает.
#
#  Почему адрес ровно один, а не все сразу.
#
#  Опция списочная, и просится перечислить зеркала через add_list. Так
#  делать нельзя, и это проверка на стенде, а не предположение:
#  PassWall скачивает ВСЕ адреса, но при отказе любого ставит sret=1 и
#  выбрасывает результат целиком — вместе с тем, что успешно скачалось
#  с живых (rule_update.lua, ветка «部分或全部资源无法下载»). Урезали
#  chnlist до 50 строк, дали рабочее зеркало и мёртвый адрес, запустили
#  обновление — список остался на пятидесяти строках. То есть каждое
#  добавленное зеркало не страхует, а повышает шанс, что обновления не
#  будет вовсе.
#
#  Запуск: из titan_pw_check.sh, который стоит в кроне у всех. Своей
#  строкой в cron не поставить — /etc/crontabs переживает sysupgrade, и
#  новые задания до проданных роутеров не доезжают никогда. А /usr/bin
#  приходит из образа целиком.
#
#  ── Чем он может помешать и что с этим сделано ──────────────────
#
#  Вызывают его раз в минуту, роутер слабый, а рядом работает туннель
#  клиента. Поэтому:
#
#  1. Метка хранит время СЛЕДУЮЩЕГО запуска, а не прошлого. Раньше
#     метка писалась только при успехе, и это значило: нет интернета —
#     значит полный перебор зеркал каждую минуту, круглосуточно. При
#     неудаче теперь тоже пишем, только ближе: смысл возвращаться
#     через десять минут есть, каждую минуту — нет.
#
#  2. Замок. Без него медленный перебор наложился бы на следующий
#     запуск по крону, и curl-ы копились бы пачками. mkdir атомарен на
#     любой файловой системе, в отличие от проверки существования.
#
#  3. Время ограничено жёстко: пять секунд на соединение, восемь на
#     попытку. Худший случай — три зеркала по восемь, 24 секунды, что
#     заведомо меньше минуты между запусками.
#
#  4. nice 19. Если роутер занят, мы уступаем всему остальному.
#
#  5. Первые две минуты после загрузки не лезем: там и без нас тесно,
#     а списки не горят.
#
#  6. Опция никогда не остаётся пустой. delete и add_list — две
#     операции, и между ними можно остаться ни с чем; пустой
#     chnlist_url означает, что PassWall возьмёт свои умолчания, то
#     есть китайские списки, то есть вывернутую маршрутизацию у
#     клиента. Поэтому после записи проверяем результат и при пустоте
#     возвращаем прежнее значение.
# ═══════════════════════════════════════════════════════════════════

set -u

LOG_TAG="titan_lists"
STAMP="/tmp/titan_lists_mirror_next"
LOCK="/tmp/titan_lists_mirror.lock"
GAP_OK=3600
GAP_FAIL=600
MIN_UPTIME=120

MIRRORS="https://storage.yandexcloud.net/234588/lists
https://titanvps.pro/lists
https://vbotrouters.titanvps.click/lists"

log() { logger -t "$LOG_TAG" "$*"; }

FORCE=0
[ "${1:-}" = "--now" ] && FORCE=1

# ── Рано после загрузки ──────────────────────────────────────────
UPTIME="$(awk '{print int($1)}' /proc/uptime 2>/dev/null || echo 0)"
if [ "$FORCE" = 0 ] && [ "$UPTIME" -lt "$MIN_UPTIME" ]; then
    exit 0
fi

NOW="$(date +%s)"

# ── Ещё не время ─────────────────────────────────────────────────
# Самый частый путь: одно чтение файла и сравнение чисел.
if [ "$FORCE" = 0 ] && [ -f "$STAMP" ]; then
    NEXT="$(cat "$STAMP" 2>/dev/null | tr -dc '0-9')"
    case "${NEXT:-}" in
        ""|*[!0-9]*) : ;;
        *) [ "$NOW" -lt "$NEXT" ] && exit 0 ;;
    esac
fi

# ── Замок ────────────────────────────────────────────────────────
# Брошенный замок старше пяти минут снимаем: столько работа занять не
# может даже при трёх мёртвых зеркалах.
if ! mkdir "$LOCK" 2>/dev/null; then
    if [ -d "$LOCK" ]; then
        AGE=$(( NOW - $(date -r "$LOCK" +%s 2>/dev/null || echo "$NOW") ))
        if [ "$AGE" -gt 300 ]; then
            log "снят брошенный замок (${AGE}с)"
            rm -rf "$LOCK" 2>/dev/null || true
            mkdir "$LOCK" 2>/dev/null || exit 0
        else
            exit 0
        fi
    else
        exit 0
    fi
fi
trap 'rm -rf "$LOCK" 2>/dev/null' EXIT INT TERM

# Отложить следующий запуск. Пишем СРАЗУ, до всякой работы: если нас
# прибьют посреди перебора, следующая минута не начнёт всё заново.
defer() { echo "$(( NOW + $1 ))" > "$STAMP" 2>/dev/null || true; }
defer "$GAP_FAIL"

# ── Проба ────────────────────────────────────────────────────────
# Один байт заголовком Range. Сервер, не умеющий куски, отдаст файл
# целиком — на этот случай стоит общий предел времени.
probe() {
    nice -n 19 curl -fsS --connect-timeout 5 --max-time 8 --range 0-0 \
         -o /dev/null "$1/proxy-ip.lst" 2>/dev/null
}

BASE=""
for m in $MIRRORS; do
    if probe "$m"; then
        BASE="$m"
        break
    fi
done

if [ -z "$BASE" ]; then
    # Ни одно не отозвалось — почти наверняка нет интернета вообще.
    # Конфиг не трогаем: то, что там стоит, ничем не хуже, а пустой
    # был бы хуже заведомо.
    log "ни одно зеркало не ответило — адрес оставлен прежним"
    exit 0
fi

# ── Запись ───────────────────────────────────────────────────────
CHANGED=0
for pair in "chnlist_url proxy-domains.lst" \
            "chnroute_url proxy-ip.lst" \
            "gfwlist_url proxy-domains.lst"; do
    opt="${pair%% *}"
    file="${pair##* }"
    want="$BASE/$file"
    cur="$(uci -q get passwall.@global_rules[0].$opt 2>/dev/null || true)"
    [ "$cur" = "$want" ] && continue

    uci -q delete passwall.@global_rules[0]."$opt" 2>/dev/null || true
    uci -q add_list passwall.@global_rules[0]."$opt"="$want" 2>/dev/null || true

    # Проверяем, что не остались ни с чем. Пустая опция означала бы
    # китайские списки PassWall по умолчанию и вывернутую
    # маршрутизацию у клиента — цена ошибки несопоставима со
    # стоимостью одной проверки.
    new="$(uci -q get passwall.@global_rules[0].$opt 2>/dev/null || true)"
    if [ -z "$new" ]; then
        log "$opt осталась пустой — возвращаем прежнее значение"
        uci -q delete passwall.@global_rules[0]."$opt" 2>/dev/null || true
        for old in $cur; do
            uci -q add_list passwall.@global_rules[0]."$opt"="$old" 2>/dev/null || true
        done
        continue
    fi
    CHANGED=1
done

if [ "$CHANGED" = 1 ]; then
    # Только commit. Перезапускать PassWall не надо и нельзя: службу
    # он этим не трогает (в /etc/init.d/passwall нет service_triggers),
    # а лишний перезапуск у клиента — это разрыв туннеля на ровном
    # месте. Новый адрес подхватится следующим плановым обновлением
    # списков, спешить тут некуда.
    uci -q commit passwall || true
    log "зеркало списков: $BASE"
fi

defer "$GAP_OK"
exit 0
