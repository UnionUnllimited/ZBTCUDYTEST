#!/bin/sh
# ═══════════════════════════════════════════════════════════════════
#  Управление сервисом доступа. Единственная точка записи.
#
#  Ни сервер, ни бот к uci напрямую не ходят: всё через этот скрипт.
#  Смысл в том, что запись в конфигурацию и перезапуск сервиса — это
#  одна неделимая операция. Два места, которые правят настройки
#  независимо, рано или поздно перезапустят сервис внахлёст и оставят
#  клиента на узле, которого он не выбирал.
#
#  Команды:
#    list        состояние, ничего не меняет
#    use <id>    сделать узел активным
#    on          включить сервис
#    off         выключить сервис
#
#  В stdout — ровно одна строка JSON, и при успехе, и при отказе.
#  Диагностика идёт в logger и stderr, чтобы вызывающая сторона могла
#  читать stdout как есть, не вычищая из него посторонние строки.
#
#  Код возврата 0 при успехе, 1 при отказе, но JSON печатается всегда:
#  «узла нет» — полезный ответ, «команда не выполнилась» — нет.
# ═══════════════════════════════════════════════════════════════════

# set -e здесь не нужен: почти каждая проверка имеет осмысленную ветку
# отказа, и молчаливый выход посреди операции хуже явного кода ошибки.
set -u

TAG="access_ctl"
CFG="passwall"
SVC="/etc/init.d/passwall"
FRPC="/etc/init.d/frpc"
LOCK="/tmp/access_ctl.lock"

# Сколько секунд замок считается живым. Перезапуск сервиса занимает
# около минуты; берём с запасом, но так, чтобы упавший вызов не держал
# устройство заблокированным до перезагрузки.
LOCK_MAX=120

# ── Время без внешних процессов ─────────────────────────────────
# Монотонное: в отличие от системных часов не прыгает при синхронизации
# времени, поэтому возраст замка считается верно даже сразу после
# подъёма связи, когда ntp двигает часы на часы вперёд.
uptime_s() {
	read -r _u _rest < /proc/uptime 2>/dev/null || { echo 0; return; }
	echo "${_u%%.*}"
}

log() { logger -t "$TAG" "$*"; }
err() { printf '%s\n' "$*" >&2; }

# ── JSON ────────────────────────────────────────────────────────
# Названия узлов приходят из подписки, пишем их не мы. Одна кавычка в
# remarks — и весь ответ перестаёт разбираться, поэтому экранируем.
# Порядок важен: сначала обратный слэш, иначе он удвоит уже
# подставленные экранирующие слэши.
#
# Управляющие символы заменяем пробелом, а не переводим в \uXXXX:
# сделать это в ash без внешних инструментов нечем, а в человеческом
# названии узла их и не должно быть. Задача здесь — не потерять смысл,
# а не дать сломать разбор и не разорвать ответ на две строки.
json_escape() {
	printf '%s' "$1" | sed -e 's/\\/\\\\/g' -e 's/"/\\"/g' -e 's/[[:cntrl:]]/ /g'
}

fail() {
	printf '{"ok":false,"error":"%s"}\n' "$1"
	exit 1
}

# Список секций-узлов в том порядке, в каком они лежат в конфигурации:
# uci show выдаёт их последовательно, и этот порядок клиент видит в
# списке. Сортировать нельзя — пользователь запоминает позицию.
node_ids() {
	uci -q show "$CFG" 2>/dev/null \
		| sed -n "s/^$CFG\.\([^.]*\)=nodes\$/\1/p"
}

# Активный узел. Пустая строка, если не выбран ни один.
current_node() {
	uci -q get "$CFG.@global[0].node" 2>/dev/null || true
}

# Отсутствующая настройка означает «включён» — именно так ведёт себя
# сам сервис, и ответ должен совпадать с фактическим поведением, а не
# с содержимым файла.
is_enabled() {
	[ "$(uci -q get "$CFG.@global[0].enabled" 2>/dev/null || echo 1)" != "0" ]
}

state_json() {
	_cur="$(current_node)"
	if is_enabled; then _en="true"; else _en="false"; fi

	printf '{"ok":true,"enabled":%s,"current":"%s","nodes":[' \
		"$_en" "$(json_escape "$_cur")"

	_first=1
	for _id in $(node_ids); do
		_nm="$(uci -q get "$CFG.$_id.remarks" 2>/dev/null || true)"
		[ -n "$_nm" ] || _nm="$_id"
		[ "$_first" = 1 ] || printf ','
		_first=0
		printf '{"id":"%s","name":"%s"}' \
			"$(json_escape "$_id")" "$(json_escape "$_nm")"
	done

	printf ']}\n'
}

# ── Замок ───────────────────────────────────────────────────────
# mkdir, а не flock: атомарен на любой файловой системе и есть в любой
# сборке busybox, тогда как flock собран не везде.
#
# Замок снимает не этот скрипт, а отсоединённая задача применения —
# иначе следующий вызов пришёл бы, пока сервис ещё перезапускается,
# и мы получили бы ровно тот наложенный перезапуск, от которого
# защищаемся.
lock_take() {
	if mkdir "$LOCK" 2>/dev/null; then
		uptime_s > "$LOCK/at" 2>/dev/null
		return 0
	fi

	_at="$(cat "$LOCK/at" 2>/dev/null || echo 0)"
	_now="$(uptime_s)"
	_age=$(( _now - _at ))

	# Возраст меньше нуля означает, что метка из прошлой загрузки:
	# /tmp при перезагрузке очищается, но подстраховаться дешевле,
	# чем разбираться потом с намертво заблокированным устройством.
	if [ "$_at" = 0 ] || [ "$_age" -gt "$LOCK_MAX" ] || [ "$_age" -lt 0 ]; then
		log "снимаю зависший замок, возраст ${_age}s"
		rm -rf "$LOCK" 2>/dev/null
		mkdir "$LOCK" 2>/dev/null || return 1
		uptime_s > "$LOCK/at" 2>/dev/null
		return 0
	fi

	return 1
}

lock_free() { rm -rf "$LOCK" 2>/dev/null; }

# ── Применение ──────────────────────────────────────────────────
# Перезапуск сервиса в пятнадцать секунд не укладывается — сервер
# оборвёт сессию раньше, чем он закончит. Поэтому отсоединяем: скрипт
# печатает состояние, которое получится после применения, и выходит,
# а перезапуск доигрывает сам.
#
# frpc после этого перезапускаем всегда. Это единственный путь, которым
# мы попадаем на устройство, а перезапуск сервиса и тем более его
# выключение переставляют маршруты под ним. Стоит это секунды, а цена
# ошибки — устройство, до которого больше не дотянуться.
apply_async() {
	_job="$SVC restart >/dev/null 2>&1; sleep 5; [ -x $FRPC ] && $FRPC restart >/dev/null 2>&1; rm -rf $LOCK"
	if command -v setsid >/dev/null 2>&1; then
		setsid /bin/sh -c "$_job" >/dev/null 2>&1 &
	else
		/bin/sh -c "$_job" >/dev/null 2>&1 &
	fi
}

# ── Разбор команды ──────────────────────────────────────────────
CMD="${1:-}"

uci -q show "$CFG" >/dev/null 2>&1 || {
	log "$CMD: конфигурации $CFG нет"
	err "конфигурация $CFG не найдена"
	fail "no_service"
}

case "$CMD" in

list)
	# Замок не берём: чтение ничего не меняет, а ждать освобождения
	# ради состояния — значит отвечать «занято» на безобидный запрос.
	[ -n "$(node_ids)" ] || { log "list: узлов нет"; fail "no_nodes"; }
	state_json
	exit 0
	;;

use)
	WANT="${2:-}"
	[ -n "$WANT" ] || { err "use: не указан узел"; fail "bad_usage"; }

	lock_take || { log "use $WANT: занято"; fail "busy"; }

	[ -n "$(node_ids)" ] || {
		lock_free
		log "use $WANT: узлов нет"
		fail "no_nodes"
	}

	# Аргумент пришёл от клиента через приложение — доверия ему нет.
	# Сверяем со списком посимвольно и нигде не подставляем в команду
	# без кавычек. Совпадения нет — конфигурацию не трогаем вовсе.
	FOUND=0
	for _id in $(node_ids); do
		[ "$_id" = "$WANT" ] && { FOUND=1; break; }
	done
	[ "$FOUND" = 1 ] || {
		lock_free
		log "use $WANT: такого узла нет"
		err "узел не найден: $WANT"
		fail "unknown_node"
	}

	# Узел уже активен — перезапускать сервис незачем. Это не отказ:
	# состояние ровно то, которое просили, а лишний перезапуск рвёт
	# соединения клиента на ровном месте.
	if [ "$(current_node)" = "$WANT" ]; then
		lock_free
		log "use $WANT: уже активен, перезапуск не нужен"
		state_json
		exit 0
	fi

	uci -q set "$CFG.@global[0].node=$WANT" 2>/dev/null

	# tcp_node и udp_node трогаем, только если они уже есть: свежие
	# сборки читают один node, и заводить у них лишние настройки
	# незачем, а старым без этих двух узел не сменить.
	for _o in tcp_node udp_node; do
		if uci -q get "$CFG.@global[0].$_o" >/dev/null 2>&1; then
			uci -q set "$CFG.@global[0].$_o=$WANT" 2>/dev/null
		fi
	done

	uci -q commit "$CFG" >/dev/null 2>&1 || {
		lock_free
		log "use $WANT: commit не прошёл"
		err "не удалось записать конфигурацию"
		fail "commit_failed"
	}

	apply_async
	log "use $WANT: применено"
	state_json
	exit 0
	;;

on|off)
	lock_take || { log "$CMD: занято"; fail "busy"; }

	[ "$CMD" = "on" ] && VAL=1 || VAL=0
	uci -q set "$CFG.@global[0].enabled=$VAL" 2>/dev/null
	uci -q commit "$CFG" >/dev/null 2>&1 || {
		lock_free
		log "$CMD: commit не прошёл"
		err "не удалось записать конфигурацию"
		fail "commit_failed"
	}

	apply_async
	log "$CMD: применено"
	state_json
	exit 0
	;;

*)
	err "использование: $0 list | use <id> | on | off"
	fail "bad_usage"
	;;
esac
