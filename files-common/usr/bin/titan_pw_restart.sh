#!/bin/sh
# ═══════════════════════════════════════════════════════════════════
#  Titan Router — единственная точка перезапуска PassWall
#
#  Перезапуск дорогой: заново заливаются списки в nftables, пересобирается
#  конфиг dnsmasq, поднимаются chinadns-ng и xray. А просить его умеют
#  сразу несколько сторон — vpn_watchdog, dns_watchdog, пакетный hotplug
#  на ifup, смена узла из панели.
#
#  Беда в том, что во время самого перезапуска xray и chinadns-ng
#  отсутствуют — то есть перезапуск создаёт ровно то условие, по которому
#  watchdog требует следующий перезапуск. Замкнутый круг.
#
#  29.08.2026 он сложился вживую: в 20:10:23 vpn_watchdog и dns_watchdog
#  в одну секунду запустили по рестарту, дальше нагрузка росла три окна
#  подряд (load 4.5 → 10.6 → 18.0) и роутер перестал отвечать.
#
#  Поэтому все обращаются сюда, а не к init-скрипту напрямую. Здесь лок
#  на время работы и пауза после: одновременно идёт максимум один
#  перезапуск, и не чаще раза в COOLDOWN секунд.
#
#  Запуск:
#      titan_pw_restart.sh "повод"       обычный, с паузой
#      titan_pw_restart.sh -f "повод"    без паузы, для диагностики
#
#  Когда запускает человек, скрипт объясняет свои действия на экран.
#  Из cron и watchdog'ов он молчит — им хватает syslog.
# ═══════════════════════════════════════════════════════════════════

set -u

LOG_TAG="titan_pw"
LOCK="/tmp/titan_pw_restart.lock"
STAMP="/tmp/titan_pw_restart_at"
COOLDOWN=300

FORCE=0
case "${1:-}" in
    -f|--force) FORCE=1; shift ;;
esac
REASON="${1:-повод не указан}"

# Отказ обязан быть виден тому, кто запустил руками. Раньше причина
# уходила только в syslog: человек вызывал скрипт для диагностики,
# срабатывала пауза, на экране не появлялось ничего — и выглядело это
# так, будто перезапуск прошёл. Дальше он смотрел лог, видел старые
# записи и делал неверные выводы.
log() {
    logger -t "$LOG_TAG" "$*"
    [ -t 1 ] && printf '%s\n' "$*"
    return 0
}

# ── Уже идёт ─────────────────────────────────────────────────────
if [ -f "$LOCK" ]; then
    PID="$(cat "$LOCK" 2>/dev/null)"
    if [ -n "${PID:-}" ] && [ -d "/proc/$PID" ]; then
        log "перезапуск уже идёт (pid $PID), «$REASON» пропущен"
        exit 0
    fi
fi

# ── Только что перезапускали ─────────────────────────────────────
# Сервисам нужно время подняться. Без паузы watchdog, проснувшийся сразу
# после рестарта, увидит ещё не стартовавший xray и потребует новый.
LAST="$(cat "$STAMP" 2>/dev/null | tr -dc '0-9')"
NOW="$(date +%s)"
if [ "$FORCE" = 0 ] \
   && [ -n "${LAST:-}" ] && [ "$((NOW - LAST))" -ge 0 ] && [ "$((NOW - LAST))" -lt "$COOLDOWN" ]; then
    log "перезапускали $((NOW - LAST))с назад, «$REASON» пропущен (обойти: -f)"
    exit 0
fi
[ "$FORCE" = 1 ] && log "пауза обойдена по -f"

echo $$ > "$LOCK"
trap 'rm -f "$LOCK"' EXIT INT TERM
echo "$NOW" > "$STAMP"

# ── Половинчатая таблица nftables ────────────────────────────────
# Если app.sh упал на полпути, таблица inet passwall остаётся, но без
# хук-цепочек: правила вроде PSW_DNS созданы, а заходить в них нечему —
# счётчики стоят на нуле, и клиенты остаются без DNS. Дальше каждый
# перезапуск сыплет «Could not process rule: No such file or directory»,
# само это не выправляется, лечится только сносом таблицы.
#
# Считать общее число цепочек нельзя — на этом я и обжёгся. Порог стоял
# «меньше пяти», а живьём 30.08.2026 сломанная таблица оказалась с девятью
# цепочками из тринадцати: PSW_* на месте, нет ровно четырёх хуковых.
# Проверка не срабатывала, и защита молчала при полностью мёртвом DNS.
#
# Поэтому проверяем именно те четыре, через которые трафик попадает в
# таблицу. Нет хотя бы одной — таблица нерабочая, каким бы ни был счёт.
if nft list table inet passwall >/dev/null 2>&1; then
    for _chain in dstnat mangle_prerouting mangle_output nat_output; do
        nft list chain inet passwall "$_chain" >/dev/null 2>&1 \
            || log "в таблице inet passwall нет цепочки $_chain"
    done

    # Сносим ВСЕГДА, а не только когда обнаружили поломку.
    #
    # Причина в самом PassWall. gen_nft_tables создаёт хуковые цепочки
    # исключительно при отсутствии таблицы:
    #     if ! nft list table "$NFTABLE_NAME" ...; then
    #         chain dstnat / mangle_prerouting / mangle_output / nat_output
    # Есть таблица — хуков не будет, а всё остальное спокойно допишется, и
    # скрипт отчитается «运行完成！». Значит перезапуск поверх существующей
    # таблицы в принципе не может её починить, каким бы целым ни выглядел
    # результат. Единственный способ получить правильную таблицу — отдать
    # PassWall чистое место.
    log "сносим таблицу и кэш, чтобы PassWall собрал её заново"
    nft delete table inet passwall 2>/dev/null || true

    # Одной таблицы мало: gen_include снимает с неё слепок в PSW_RULE.nft,
    # а /var/etc/passwall.include применяет его при каждой перезагрузке
    # firewall. Слепок, снятый со сломанной таблицы, воспроизводит поломку
    # бесконечно — 30.08.2026 из-за этого починка не срабатывала, пока не
    # убрали include руками. PassWall создаёт оба файла заново при старте.
    rm -f /tmp/etc/passwall/PSW_RULE.nft 2>/dev/null || true
    FWI="$(uci -q get firewall.passwall.path 2>/dev/null || true)"
    [ -n "${FWI:-}" ] && rm -f "$FWI" 2>/dev/null
    rm -f /var/etc/passwall.include 2>/dev/null || true

    /etc/init.d/firewall restart >/dev/null 2>&1 || true
    sleep 5
fi

# ── Перезапуск ───────────────────────────────────────────────────
# timeout есть не во всех сборках. Без него init-скрипт умеет виснуть на
# procd-локе и держать его до перезагрузки — с ним висящий рестарт хотя бы
# отпустит лок и следующая попытка состоится.
log "перезапускаем PassWall: $REASON"
if command -v timeout >/dev/null 2>&1; then
    timeout 180 /etc/init.d/passwall restart >/dev/null 2>&1
else
    /etc/init.d/passwall restart >/dev/null 2>&1
fi
log "перезапуск завершён"
