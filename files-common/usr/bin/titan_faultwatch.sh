#!/bin/sh
# ═══════════════════════════════════════════════════════════════════
#  Titan Router — самописец сбоев
#
#  Ловит то, что нельзя поймать входом по SSH: роутер в эти минуты не
#  отвечает ни на SSH, ни на HTTP. Соединение принимает ядро, а демоны
#  молчат — значит userspace встал, и войти, чтобы посмотреть, нельзя
#  ровно тогда, когда это нужно.
#
#  13.09.2026 на стенде за день: перезагрузка без записи в pstore (то
#  есть не паника ядра, а сброс по сторожевому таймеру — UBIFS каждый
#  раз поднимается через recovery) и отдельный затык на несколько
#  минут, который рассосался сам.
#
#  Пишет две вещи.
#
#  Пульс — раз в минуту в /tmp. Строка с временем, аптаймом, нагрузкой
#  и памятью. Ляжет роутер — пульс прервётся, и по последней строке
#  перед разрывом видно, что было прямо перед тем.
#
#  Отчёт — в /etc, только когда есть что сказать: обнаружен разрыв
#  пульса или роутер только что загрузился. /etc переживает
#  перезагрузку, /tmp нет, а интересное случается как раз вокруг неё.
#
#  Почему пульс не в /etc: минутная запись во флеш — это 1440 циклов в
#  сутки на ровном месте. Флеш тут NAND, и тратить её ради строк,
#  которые в 99 случаях из 100 никому не понадобятся, незачем.
# ═══════════════════════════════════════════════════════════════════

set -u

BEAT="/tmp/titan_beat"
REPORT="/etc/titan_faults.log"
GAP=180          # разрыв пульса, с которого считаем это сбоем
MAX_LINES=400    # сколько строк отчёта храним

NOW="$(date +%s)"
UP="$(awk '{print int($1)}' /proc/uptime 2>/dev/null || echo 0)"
LOAD="$(cut -d' ' -f1-3 /proc/loadavg 2>/dev/null)"
MEM="$(awk '/MemAvailable/{a=$2} /SwapFree/{sf=$2} /SwapTotal/{st=$2} END{printf "доступно %dМБ, swap занят %dМБ", a/1024, (st-sf)/1024}' /proc/meminfo 2>/dev/null)"

say() {
    printf '%s %s\n' "$(date '+%F %T')" "$1" >> "$REPORT" 2>/dev/null || return 0
    # Подрезаем, чтобы файл не рос без конца.
    if [ "$(wc -l < "$REPORT" 2>/dev/null || echo 0)" -gt "$MAX_LINES" ]; then
        tail -n $((MAX_LINES / 2)) "$REPORT" > "$REPORT.tmp" 2>/dev/null \
            && mv "$REPORT.tmp" "$REPORT" 2>/dev/null
    fi
}

snapshot() {
    {
        echo "    аптайм ${UP}с, нагрузка $LOAD, $MEM"
        echo "    процессов: $(ls -d /proc/[0-9]* 2>/dev/null | wc -l)"
        # Процессы в непрерываемом ожидании — верный признак, что всё
        # уперлось в диск.
        D="$(awk '{print $3}' /proc/[0-9]*/stat 2>/dev/null | grep -c D)"
        echo "    в ожидании диска (D): ${D:-0}"
        echo "    топ по памяти: $(ps w 2>/dev/null | sort -rn -k3 | head -3 | awk '{printf "%s(%s) ", $5, $3}')"
    } >> "$REPORT" 2>/dev/null || true
}

# ── Загрузка ─────────────────────────────────────────────────────
# Считаем загрузкой первые две минуты: пульса ещё нет, и отличить
# «только включились» от «был разрыв» больше нечем.
if [ "$UP" -lt 120 ]; then
    if [ ! -f "$BEAT.booted" ]; then
        : > "$BEAT.booted" 2>/dev/null || true
        REC=""
        dmesg 2>/dev/null | grep -q 'recovery needed' && REC=" (UBIFS поднялась через recovery — выключение было нечистым)"
        PST=""
        [ -n "$(ls -A /sys/fs/pstore/ 2>/dev/null)" ] && PST=" ВНИМАНИЕ: в pstore есть запись об аварии ядра"
        say "загрузка${REC}${PST}"
        snapshot
    fi
fi

# ── Разрыв пульса ────────────────────────────────────────────────
if [ -f "$BEAT" ]; then
    LAST="$(awk '{print $1}' "$BEAT" 2>/dev/null | tr -dc '0-9')"
    LASTLINE="$(cat "$BEAT" 2>/dev/null)"
    case "${LAST:-}" in
        ""|*[!0-9]*) : ;;
        *)
            DIFF=$((NOW - LAST))
            if [ "$DIFF" -gt "$GAP" ] && [ "$UP" -gt "$DIFF" ]; then
                # Аптайм больше разрыва — значит перезагрузки не было,
                # роутер просто молчал. Это и есть затык.
                say "ЗАТЫК: пульса не было ${DIFF}с, перезагрузки не было"
                say "    последнее перед затыком: $LASTLINE"
                snapshot
            fi
            ;;
    esac
fi

# ── Пульс ────────────────────────────────────────────────────────
printf '%s аптайм=%s нагрузка=%s %s\n' "$NOW" "$UP" "$LOAD" "$MEM" > "$BEAT" 2>/dev/null || true

exit 0
