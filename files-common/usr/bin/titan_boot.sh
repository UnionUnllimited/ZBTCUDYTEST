#!/bin/sh
# ═══════════════════════════════════════════════════════════════════
#  Titan Router — всё, что делается при загрузке
#
#  Вынесено сюда из /etc/rc.local, и вот почему это принципиально.
#
#  /etc/rc.local перечислен в /lib/upgrade/keep.d — то есть sysupgrade
#  его сохраняет. Значит на любом уже прошитом роутере он остаётся тем,
#  с которым устройство прошили ПЕРВЫЙ раз, и никакая последующая
#  прошивка его не меняет. Все наши правки в нём за всё время до
#  работающих роутеров не доехали.
#
#  Вскрылось 31.08.2026: нашёлся роутер, который стучался на
#  origin.all-streams-24.ru — адрес, заменённый на pandora361.online
#  задолго до того. Прошивки он получал, а rc.local — нет.
#
#  /usr/bin в keep.d не входит и целиком приезжает из образа. Поэтому
#  здесь может лежать что угодно и меняться сколько угодно, а rc.local
#  сводится к одной строке вызова и больше правок не требует никогда.
# ═══════════════════════════════════════════════════════════════════

LOG_TAG="titan_boot"

# confdir из /etc/config/dhcp обязан существовать, иначе dnsmasq не
# стартует вообще и валится в crash loop. Каталог держится на одном
# файле atlanta.conf — если тот пропал, каталог исчезает вместе с ним.
mkdir -p /etc/dnsmasq.d

MAC=$(cat /sys/class/net/br-lan/address 2>/dev/null | tr -d ':' | tr 'A-F' 'a-f')
if [ -z "$MAC" ]; then
    logger -t "$LOG_TAG" "нет MAC br-lan — пароль и FRP не настроены"
    exit 0
fi

# ── Пароль root по MAC ───────────────────────────────────────────
# Сбой openssl не должен мешать настройке FRP: иначе роутер молча
# останется без удалённого доступа, и заметить это будет нечем.
PASS=$(printf '%stests' "$MAC" | sha256sum | cut -c1-16)
HASH=$(openssl passwd -6 "$PASS" 2>/dev/null)
if [ -n "$HASH" ]; then
    sed -i "s|^root:[^:]*:|root:${HASH}:|" /etc/shadow
    echo "$PASS" > /tmp/root_pass.txt
else
    logger -t "$LOG_TAG" "openssl не отработал — пароль root не обновлён"
fi

# ── FRP ──────────────────────────────────────────────────────────
# Конфиг собирает titan_frpc_conf.sh, туда же ходит frpc_watchdog.sh.
/usr/bin/titan_frpc_conf.sh --force
/etc/init.d/frpc restart

# Проверку таблицы nftables здесь не делаем.
# Пробовали — фоновый блок с sleep не переживает завершения rc.local,
# procd прибивает группу процессов. Сторож живёт в cron:
# usr/bin/titan_pw_check.sh, раз в минуту.

exit 0
