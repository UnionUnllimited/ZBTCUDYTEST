#!/bin/sh
# ═══════════════════════════════════════════════════════════════════
#  Titan Router — списки маршрутизации после обновления прошивки
#
#  Была проблема. Файлы chnlist и chnroute лежат в /usr/share/passwall/
#  rules и входят в пакет PassWall, поэтому sysupgrade клал туда версии
#  из образа: 112 тысяч китайских доменов и 4 тысячи китайских сетей.
#  А у нас chn_list переключён в режим proxy, то есть в туннель уходит
#  ровно то, что в этих файлах. После каждого обновления маршрутизация
#  оказывалась вывернутой наизнанку: китайские сайты шли через наш
#  сервер, а YouTube с Telegram — напрямую и не открывались. Своё
#  содержимое приезжало только со следующим тиком Loop Mode, а он раз в
#  12 часов, и всё это время роутер у клиента не работал.
#
#  Лечили это здесь: скрипт замечал, что списки совпадают с теми, что
#  в /rom, ждал сети и скачивал наши.
#
#  Теперь лечение перенесено на шаг раньше: наши списки лежат прямо в
#  образе, в files-common/usr/share/passwall/rules. ImageBuilder кладёт
#  их поверх файлов пакета, поэтому роутер приходит с правильной
#  маршрутизацией с первой секунды после прошивки, и ждать нечего.
#
#  Сравнение с /rom вместе с этим потеряло смысл и стало опасным: в
#  /rom теперь лежат те же наши списки, файлы совпадают с ним всегда, и
#  прежняя проверка считала бы это поломкой каждую минуту без конца.
#
#  Что осталось. Списки в образе застывают на дате сборки, поэтому один
#  раз после прошивки подтягиваем свежие. Это уже не спасение от
#  поломки, а обычное освежение, и относиться к нему надо соответственно:
#  не вышло — не страшно, следующий тик Loop Mode всё равно придёт.
#  Поэтому метку ставим в любом случае и больше не возвращаемся.
#
#  Почему вызов из titan_pw_check.sh, а не своей строкой в cron.
#  /etc/crontabs входит в список сохраняемого при sysupgrade, поэтому
#  новые задания до уже проданных роутеров не доезжают никогда — на
#  стенде там до сих пор расписание годичной давности. А /usr/bin
#  приходит из образа, и titan_pw_check.sh уже стоит в кроне у всех.
#  Вызов оттуда — способ доставить проверку на устройства в поле.
#
#  Метка о выполнении лежит в /etc и не входит в сохраняемое, поэтому
#  обновление прошивки её стирает — ровно тогда, когда освежение снова
#  нужно. Заводской сброс и первая прошивка обрабатываются тем же.
# ═══════════════════════════════════════════════════════════════════

set -u

LOG_TAG="titan_rules"
STAMP="/etc/titan_rules_ok"
CHNLIST="/usr/share/passwall/rules/chnlist"
MIN_UPTIME=300

# Уже освежали после этой прошивки — выходим сразу. Это самый частый
# путь, он не должен стоить ничего: одна проверка существования файла.
[ -f "$STAMP" ] && exit 0

# Нет самого файла — PassWall не установлен или образ собран неполно.
# Качать в пустоту незачем, но и возвращаться сюда каждую минуту тоже.
if [ ! -f "$CHNLIST" ]; then
    logger -t "$LOG_TAG" "$CHNLIST не найден — освежение пропущено"
    touch "$STAMP" 2>/dev/null || true
    exit 0
fi

# Даём подняться сети и PassWall: у него минута задержки старта, плюс
# время на сборку правил. Раньше пяти минут дёргать обновление
# бессмысленно, оно упрётся в отсутствие маршрута.
UPTIME="$(awk '{print int($1)}' /proc/uptime 2>/dev/null || echo 0)"
[ "$UPTIME" -ge "$MIN_UPTIME" ] || exit 0

# Без связи качать нечего. Метку не ставим — вернёмся через минуту.
# Это единственный случай, когда мы сюда возвращаемся: сети может не
# быть первые минуты, и списывать это в неудачу рано.
ping -c 1 -W 3 1.1.1.1 >/dev/null 2>&1 || exit 0

BEFORE="$(md5sum "$CHNLIST" 2>/dev/null | awk '{print $1}')"
logger -t "$LOG_TAG" "освежаем списки после прошивки"
lua /usr/share/passwall/rule_update.lua log >/dev/null 2>&1 || true
AFTER="$(md5sum "$CHNLIST" 2>/dev/null | awk '{print $1}')"

if [ "$BEFORE" != "$AFTER" ]; then
    logger -t "$LOG_TAG" "списки обновились до свежих"
else
    logger -t "$LOG_TAG" "списки из образа уже свежие либо сервер не ответил"
fi

# Метка в любом случае: в образе лежат рабочие списки, и повторять
# попытку каждую минуту не за чем — маршрутизация не сломана.
touch "$STAMP" 2>/dev/null || true

exit 0
