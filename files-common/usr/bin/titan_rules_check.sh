#!/bin/sh
# ═══════════════════════════════════════════════════════════════════
#  Titan Router — списки маршрутизации после обновления прошивки
#
#  Проблема. Файлы chnlist и chnroute лежат в /usr/share/passwall/rules
#  и входят в пакет PassWall, поэтому sysupgrade кладёт туда версии из
#  образа: 112 тысяч китайских доменов и 4 тысячи китайских сетей.
#  А у нас chn_list переключён в режим proxy, то есть в туннель уходит
#  ровно то, что в этих файлах. После каждого обновления маршрутизация
#  оказывается вывернутой наизнанку: китайские сайты идут через наш
#  сервер, а YouTube с Telegram — напрямую и не открываются.
#
#  Своё содержимое приезжает только со следующим тиком Loop Mode у
#  PassWall, а он раз в 12 часов. Всё это время роутер у клиента не
#  работает так, как должен.
#
#  Почему вызов отсюда, а не своей строкой в cron. /etc/crontabs входит
#  в список сохраняемого при sysupgrade, поэтому новые задания до уже
#  проданных роутеров не доезжают никогда — на стенде там до сих пор
#  расписание годичной давности. А /usr/bin приходит из образа, и
#  titan_pw_check.sh уже стоит в кроне у всех. Вызов оттуда — способ
#  доставить проверку на устройства, которые в поле.
#
#  Метка о выполнении лежит в /etc и не входит в сохраняемое, поэтому
#  обновление прошивки её стирает — ровно тогда, когда проверка снова
#  нужна. Заводской сброс и первая прошивка обрабатываются тем же.
# ═══════════════════════════════════════════════════════════════════

set -u

LOG_TAG="titan_rules"
STAMP="/etc/titan_rules_ok"
CHNLIST="/usr/share/passwall/rules/chnlist"
ROM_CHNLIST="/rom/usr/share/passwall/rules/chnlist"
MIN_UPTIME=300

# Уже разбирались после этой прошивки — выходим сразу. Это самый частый
# путь, он не должен стоить ничего: одна проверка существования файла.
[ -f "$STAMP" ] && exit 0

# Списки совпадают с теми, что в образе — значит они стоковые и своих мы
# ещё не скачали. Сравнение с /rom самодостаточно: не надо ни считать
# строки, ни держать список опорных доменов, который придётся
# поддерживать. Если /rom недоступен (сборка не squashfs), считаем, что
# списки в порядке, и больше не возвращаемся.
if [ ! -f "$ROM_CHNLIST" ] || ! cmp -s "$CHNLIST" "$ROM_CHNLIST"; then
    touch "$STAMP" 2>/dev/null || true
    exit 0
fi

# Даём подняться сети и PassWall: у него минута задержки старта, плюс
# время на сборку правил. Раньше пяти минут дёргать обновление
# бессмысленно, оно упрётся в отсутствие маршрута.
UPTIME="$(awk '{print int($1)}' /proc/uptime 2>/dev/null || echo 0)"
[ "$UPTIME" -ge "$MIN_UPTIME" ] || exit 0

# Без связи качать нечего. Метку не ставим — вернёмся через минуту.
ping -c 1 -W 3 1.1.1.1 >/dev/null 2>&1 || exit 0

logger -t "$LOG_TAG" "списки стоковые после обновления — качаем свои"
lua /usr/share/passwall/rule_update.lua log >/dev/null 2>&1 || true

# Метку ставим только если файлы действительно перестали совпадать с
# образом. Иначе следующая минута попробует снова: сервер списков мог
# быть недоступен, и записывать успех в этом случае нельзя.
if ! cmp -s "$CHNLIST" "$ROM_CHNLIST"; then
    touch "$STAMP" 2>/dev/null || true
    logger -t "$LOG_TAG" "списки обновлены, маршрутизация восстановлена"
else
    logger -t "$LOG_TAG" "обновить не удалось, повтор через минуту"
fi

exit 0
